"""Qwen3-8B variant tests for MXFP8 matrix multiplication kernel.

Tests the Qwen3-8B model shapes under different input configurations:
pre-quantized, pre-swizzled, unswizzled BF16, and spill-reload.
"""

import numpy as np
import pytest

from nkilib_src.nkilib.experimental.matmul_mxfp8 import matmul_mxfp8_generic_kernel
from nkilib_src.nkilib.experimental.matmul_mxfp8.matmul_mxfp8_torch import matmul_mxfp8_torch_ref
from test.integration.nkilib.experimental.matmul_mxfp8 import (
    config_helper,
    constants,
    model_config_reader,
)
from test.integration.nkilib.experimental.matmul_mxfp8.test_matmul_mxfp8_generic_kernel import (
    _mxfp8_comparator,
    build_matmul_inputs,
    get_output_dtype,
)
from test.utils import common_dataclasses
from test.utils.pytest_test_metadata import pytest_test_metadata
from test.utils.unit_test_framework import UnitTestFramework


def populate_tests(grid, auto_generate_default=False):
    """Populate test configurations from a grid of base configs.

    When auto_generate_default is True, uses autoGenerateDefault() which
    produces a single deterministic configuration per grid entry.
    Otherwise falls back to autoGenerateRandomSubset().
    """
    res = []
    for conf in grid:
        if auto_generate_default:
            res += conf.autoGenerateDefault()
        else:
            res += conf.autoGenerateRandomSubset(3)
    return res


def _make_qwen_configs(run_with_lnc2=None, enable_scale_packing=True, **overrides):
    """Create Qwen3-8B configs with overrides applied BEFORE autoGenerateDefault.

    run_with_lnc2 defaults to None so autoGenerateDefault will try LNC2 first
    and fall back to LNC1 when the shape doesn't support it.
    """
    base_configs = model_config_reader.qwen3_8b_tp4
    configs = []
    for base in base_configs:
        conf = config_helper.TestConfig(
            M=base.M,
            K=base.K,
            N=base.N,
            description=base.description,
            run_with_lnc2=run_with_lnc2,
            enable_scale_packing=enable_scale_packing,
            **overrides,
        )
        configs.append(conf)
    return populate_tests(configs, auto_generate_default=True)


# Case 1: Pre-quantized (MXFP8) + swizzled + LNC2, no spill reload
GRID_PREQUANTIZED_SWIZZLED = _make_qwen_configs(
    lhs_dtype=constants.MatrixPrecision.MXFP8,
    rhs_dtype=constants.MatrixPrecision.MXFP8,
    lhs_is_swizzled=True,
    rhs_is_swizzled=True,
    spill_reload=False,
    enable_scale_packing=True,
)

