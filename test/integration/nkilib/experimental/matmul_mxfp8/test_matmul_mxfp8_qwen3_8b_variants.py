# Case 6: Unswizzled BF16 (not quantized, not swizzled) + LNC2
def _make_unswizzled_bf16_configs():
    """Create unswizzled BF16 configs requiring tile_m=128, tile_k=512, TILES_IN_LOAD_M=4, TILES_IN_LOAD_N=1."""
    base_configs = model_config_reader.qwen3_8b_tp4
    configs = []
    for base in base_configs:
        # Unswizzled (DGT) requires tile_k=512; skip shapes where K < 512
        if base.K < 512:
            continue
        # tile_n=512 for DGT when N >= 512, otherwise tile_n=N
        tile_n = 512 if base.N >= 512 else base.N
        conf = config_helper.TestConfig(
            M=base.M,
            K=base.K,
            N=base.N,
            description=base.description,
            run_with_lnc2=None,
            enable_scale_packing=False,
            lhs_dtype=constants.MatrixPrecision.BFLOAT16,
            rhs_dtype=constants.MatrixPrecision.BFLOAT16,
            lhs_is_swizzled=False,
            rhs_is_swizzled=False,
            tile_m=128,
            tile_n=tile_n,
            tile_k=512,
            TILES_IN_LOAD_M=4,
            TILES_IN_LOAD_N=1,
            spill_reload=True,
        )
        configs.append(conf)
    return populate_tests(configs, auto_generate_default=True)


GRID_UNSWIZZLED_BF16 = _make_unswizzled_bf16_configs()


@pytest_test_metadata(
    name="Matmul MXFP8 Qwen3-8B Variants",
)
@pytest.mark.platforms(exclude=[common_dataclasses.Platforms.TRN1, common_dataclasses.Platforms.TRN2])
class TestMatmulMxfp8Qwen38bVariants:
    """Qwen3-8B model shape tests under different input configurations."""

    def _run_test(self, test_manager, conf, platform_target, gpu_golden_enabled=False):
        if not platform_target.is_trn3():
            pytest.skip("MX is only supported on TRN3.")

        compiler_args = common_dataclasses.CompilerArgs(
            logical_nc_config=2 if conf.run_with_lnc2 else 1,
            platform_target=platform_target,
            additional_cmd_args=["--internal-backend-options=--enable-mx-alternative-emax"],
        )

        test_manager.collector.set_kernel_params(conf.to_metrics_dict())
        output_dtype = get_output_dtype(conf)

        def input_generator(test_config):
            return build_matmul_inputs(conf)

        def output_tensors(kernel_input):
            return {"out": np.zeros((conf.M, conf.N), dtype=output_dtype)}

        framework = UnitTestFramework(
            test_manager=test_manager,
            kernel_entry=matmul_mxfp8_generic_kernel.matmul_mxfp8,
            torch_ref=matmul_mxfp8_torch_ref,
            kernel_input_generator=input_generator,
            output_tensor_descriptor=output_tensors,
        )
        framework.run_test(
            test_config=None,
            compiler_args=compiler_args,
            custom_comparator=_mxfp8_comparator(conf, output_dtype, gpu_golden_enabled),
        )

    @pytest.mark.parametrize("conf", GRID_PREQUANTIZED_SWIZZLED)
    def test_qwen3_8b_prequantized_swizzled(self, test_manager, conf, platform_target):
        """Case 1: Pre-quantized MXFP8 + swizzled, no spill reload."""
        self._run_test(test_manager, conf, platform_target)

    @pytest.mark.parametrize("conf", GRID_SWIZZLED_BF16_NO_SCALE_PACKING)
    def test_qwen3_8b_swizzled_bf16_no_scale_packing(self, test_manager, conf, platform_target):
        """Case 2: Pre-swizzled BF16, no scale packing, no spill reload."""
        self._run_test(test_manager, conf, platform_target)

    @pytest.mark.parametrize("conf", GRID_SWIZZLED_BF16_SCALE_PACKING)
    def test_qwen3_8b_swizzled_bf16_scale_packing(self, test_manager, conf, platform_target):
        """Case 3: Pre-swizzled BF16, scale packing enabled, no spill reload."""
        self._run_test(test_manager, conf, platform_target)

    @pytest.mark.parametrize("conf", GRID_SWIZZLED_BF16_SPILL_RELOAD)
    def test_qwen3_8b_swizzled_bf16_spill_reload(self, test_manager, conf, platform_target):
        """Case 4: Pre-swizzled BF16, no scale packing, spill reload enabled."""
        self._run_test(test_manager, conf, platform_target)

    @pytest.mark.parametrize("conf", GRID_SWIZZLED_BF16_SCALE_PACKING_SPILL_RELOAD)
    def test_qwen3_8b_swizzled_bf16_scale_packing_spill_reload(self, test_manager, conf, platform_target):
        """Case 5: Pre-swizzled BF16, BOTH scale packing and spill reload."""
        self._run_test(test_manager, conf, platform_target)

    @pytest.mark.parametrize("conf", GRID_UNSWIZZLED_BF16)
    def test_qwen3_8b_unswizzled_bf16(self, test_manager, conf, platform_target):
        """Case 6: Unswizzled BF16 (not quantized, not swizzled)."""
        self._run_test(test_manager, conf, platform_target)
